const CRC_TABLE = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();

function crc32(buf) {
  let c = -1;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([len, body, crc]);
}

/* Render `text` to a greyscale PNG at `scale` pixels per font pixel. */
function renderPng(text, scale = 3) {
  const chars = text.toUpperCase().split("");
  const glyphW = 6; // 5 columns + 1 spacing
  const width = chars.length * glyphW * scale;
  const height = 7 * scale + 2 * scale;

  // Greyscale, 8-bit: one filter byte (0 = None) per scanline.
  const raw = Buffer.alloc((width + 1) * height, 0xff);
  for (let y = 0; y < height; y++) raw[y * (width + 1)] = 0;

  const setPixel = (x, y) => {
    if (x < 0 || y < 0 || x >= width || y >= height) return;
    raw[y * (width + 1) + 1 + x] = 0x00;
  };

  chars.forEach((ch, ci) => {
    const glyph = FONT[ch] || FONT[" "];
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (!(glyph[row] & (1 << (4 - col)))) continue;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            setPixel((ci * glyphW + col) * scale + dx, (row + 1) * scale + dy);
          }
        }
      }
    }
  });

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;  // bit depth
  ihdr[9] = 0;  // colour type: greyscale
  ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

/* Guard 55: a digit sprite sheet — 0-9 laid out horizontally. The page shows
 * numbers purely as background-position offsets into this image, so no numeric
 * text exists in the DOM at all. */
function digitSprite(scale = 3) {
  return { png: renderPng("0123456789", scale), cellWidth: 6 * scale, height: 9 * scale };
}

/* 1x1 transparent-ish pixel used as a subresource beacon (guard 48). */
function beaconPng() {
  return renderPng(" ", 1);
}

module.exports = { renderPng, digitSprite, beaconPng, FONT };
