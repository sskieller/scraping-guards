/* Guard 56 support: render text to a real PNG with no text anywhere in the file.
 *
 * The canvas guard (4) still shipped its string to the client to draw. Here the
 * server rasterises with a built-in 5x7 bitmap font and sends only pixels, so
 * the string exists nowhere in the response — OCR or a vision model is the only
 * way in. Zero dependencies: PNG is assembled by hand over zlib.
 *
 * Accessibility warning: image-only text is invisible to screen readers. On a
 * real site this needs an accessible alternative, which necessarily weakens the
 * guard. That trade-off is the point of having it in a test suite.
 */
"use strict";
const zlib = require("zlib");

